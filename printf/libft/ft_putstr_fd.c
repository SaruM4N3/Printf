#include <unistd.h>

void	ft_putstr_fd(char *s, int fd)
{
	int	i;

	i = 0;
	if (!s || fd < 0)
		return ;
	while (s[i])
	{
		if (write(fd, &s[i], 1) < 0)
			return ;
		i++;
	}
}
